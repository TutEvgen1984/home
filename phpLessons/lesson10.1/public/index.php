  // Двоичный (бинарный) поиск (также известен как метод деления пополам или дихотомия) — классический алгоритм поиска элемента в отсортированном массиве (векторе), использующий дробление массива на половины. Используется в информатике, вычислительной математике и математическом программировании.
  // Частным случаем двоичного поиска является метод бисекции, который применяется для поиска корней заданной непрерывной функции на заданном отрезке.

  // https: //rutube.ru/video/5e57370f1078c9dce31915f262e6fe9d/?r=wd
  // https://ru.wikipedia.org/wiki/Двоичный_поиск#:~:text=Двоичный%20(бинарный)%20поиск%20(также%20известен,непрерывной%20функции%20на%20заданном%20отрезке

  // $array - это массив, в котором будем искать. массив упорядочен (отсортирован) и его элементы идут слева направо в порядке возрастания
  // $item - это элемент который будем искать
  function binary_search($array, $item)
  {
    // шагать начинаем с 0
    $step = 0;

    // нижний индекс в массиве равен 0
    $low = 0;

    // верхний индекс в массиве равен количеству элементов в массиве -1 (-1 так как индексы нумеруются с 0)
    $high = count($array) - 1;

    // цикл
    while ($low <= $high) {
      $step += 1;
      $mid = floor(($low + $high) / 2);
      $quess = $array[$mid];
      if ($quess == $item) {
        return [$step, $mid];
      }
      if ($quess > $item) {
        $high = $mid - 1;
      } else {
        $low = $mid + 1;
      }
    }
    return null;
  }

  $array = [];
  for ($i = 0; $i < 512; $i++) {
    $array[] = $i;
    // присвоение массиву без индекса значения означает автоматическое добавление в массив по порядку с авто-индексацией
  }
  // Array
  // (
  //     [0] => 0
  //     [1] => 1
  //     [2] => 2
  //     ...
  // )

  for ($i = 0; $i < 512; $i++) {
    $res = binary_search($array, $i);
    echo "На поиск элемента $i ушло шагов: $res[0]<br>";
  }

